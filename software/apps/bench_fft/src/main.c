static int16_t buf[2 * NINPUTS];

/* ---- FFT core ---- */

static void fft(int16_t *data, int len)
{
    int max = len;
    len <<= 1;
    int wstep = 1;

    while (max > 2) {
        const int16_t *wpr = wprBase;
        const int16_t *wpi = wpiBase;

        for (int m = 0; m < max; m += 2) {
            int16_t wr = *wpr;
            int16_t wi = *wpi;
            wpr += wstep;
            wpi += wstep;

            int step = max << 1;
            for (int i = m; i < len; i += step) {
                int j = i + max;
                int16_t tr = data[i] - data[j];
                int16_t ti = data[i+1] - data[j+1];
                data[i]   += data[j];
                data[i+1] += data[j+1];
                int xr = ((wr * tr + wi * ti) << 1) + 0x8000;
                int xi = ((wr * ti - wi * tr) << 1) + 0x8000;
                data[j]   = xr >> 16;
                data[j+1] = xi >> 16;
            }
        }
        max >>= 1;
        wstep <<= 1;
    }

    {
        int step = max << 1;
        for (int i = 0; i < len; i += step) {
            int j = i + max;
            int16_t tr = data[i] - data[j];
            int16_t ti = data[i+1] - data[j+1];
            data[i]   += data[j];
            data[i+1] += data[j+1];
            data[j]   = tr;
            data[j+1] = ti;
        }
    }

    /* Bit-reversal permutation */
    int16_t *d = data - 1;
    int j = 1;
    for (int i = 1; i < len; i += 2) {
        if (j > i) {
            int16_t tmp;
            tmp = d[j]; d[j] = d[i]; d[i] = tmp;
            tmp = d[j+1]; d[j+1] = d[i+1]; d[i+1] = tmp;
        }
        int m = len >> 1;
        while (m >= 2 && j > m) { j -= m; m >>= 1; }
        j += m;
    }
}

#define NUM_ITER 5

int main()
{
    RAL.SYSCFG->LSPA.UART[0].MR = 1;
    while (RAL.SYSCFG->LSPA.UART[0].MR);
    uart_init(&uart);

    enable_mcycle();

    printf("=== Benchmark: FFT 256-point ===\n");

    uint32_t cycles[NUM_ITER];

    for (int n = 0; n < NUM_ITER; n++) {
        /* Re-init input data */
        for (int i = 0; i < NINPUTS; i++) {
            buf[2*i]     = dataR[i];
            buf[2*i + 1] = dataI[i];
        }

        uint32_t start = read_mcycle();
        fft(buf, NINPUTS);
        uint32_t end = read_mcycle();

        cycles[n] = end - start;
    }

    for (int n = 0; n < NUM_ITER; n++) {
        printf("  iter %d: %lu cycles\n", n, (unsigned long)cycles[n]);
    }

    printf("Done.\n");
    while (1) {}
}
